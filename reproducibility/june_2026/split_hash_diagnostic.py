#!/usr/bin/env python3
"""Find the per-platform hash offsets under which build_balanced_split regenerates the archived June split.

build_balanced_split seeds trace assignment with `seed + hash(vehicle_model) % 997`. Python randomises str
hashes per process unless PYTHONHASHSEED is set, so the June split cannot be regenerated by rerunning the
script. Each platform's assignment depends only on its own offset, so every offset 0..996 is tried per
platform with `hash` replaced inside the split module. Run with cwd = TREE after the preprocess stage.
"""

from __future__ import annotations

import argparse
import io
import sys
from pathlib import Path

import pandas as pd

ORIG = "new_experiments/final_end_to_end_publication_run/manifests/window_manifest.csv"
JUNE_SPLIT = "_june_reference/new_experiments/final_end_to_end_publication_run_balanced/manifests/balanced_split_manifest.csv"


def canon(df: pd.DataFrame, maps: list[tuple[str, str]]) -> pd.DataFrame:
    """CSV round-trip for identical dtypes; validation_status is dropped because a single-platform call
    reports the other platforms as missing."""
    buf = io.StringIO()
    df.drop(columns=["validation_status"]).to_csv(buf, index=False)
    buf.seek(0)
    out = pd.read_csv(buf)
    for c in out.columns:
        if out[c].dtype == object:
            for old, new in maps:
                out[c] = out[c].str.replace(old, new, regex=False)
    return out.sort_values(list(out.columns)).reset_index(drop=True).astype(str)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--path-map", action="append", default=[], help="REPRO_PREFIX=JUNE_PREFIX")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    maps = [tuple(m.split("=", 1)) for m in args.path_map]
    sys.path.insert(0, str(Path.cwd()))
    import src.experiments.final_end_to_end_publication_run_balanced.balanced_split as bs

    wm = pd.read_csv(ORIG)
    june = pd.read_csv(JUNE_SPLIT)
    rows = []
    for vm in bs.PLATFORMS:
        sub = wm[wm.vehicle_model == vm]
        ref = canon(june[june.vehicle_model == vm], [])
        matches = []
        for offset in range(997):
            bs.hash = lambda _s, _o=offset: _o
            _, split, _, _ = bs.build_balanced_split(sub, seed=42)
            cand = split[split.vehicle_model == vm]
            if canon(cand, maps).equals(ref):
                matches.append(offset)
        del bs.hash
        rows.append(dict(vehicle_model=vm, matching_offsets=" ".join(map(str, matches)), n_matching=len(matches)))
        print(rows[-1], flush=True)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(args.out, index=False)
    return 0 if all(r["n_matching"] for r in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
